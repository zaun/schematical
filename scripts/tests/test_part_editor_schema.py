class SourceTests(unittest.TestCase):
    def test_strip_comments_drops_both_kinds(self):
        self.assertEqual(pes.strip_comments('a /* "x"\n */ b // "y"\nc'), 'a  b \nc')

    def test_kind_files_lists_serial_sources_for_serial(self):
        with tempfile.TemporaryDirectory() as tmp:
            for name in ('serial.c', 'ns16550_regs.c', 'serial.h', 'other.c', 'serial_acia.c'):
                write(tmp, 'backend/src/models/' + name, '')
            self.assertEqual(pes.kind_files(tmp, 'serial'), ['ns16550_regs.c', 'serial.c', 'serial_acia.c'])
            self.assertEqual(pes.kind_files(tmp, 'mux'), ['mux.c', 'mux_stored.c', 'seq.c'])

    def test_source_keys_reads_key_extra_and_timing_arrays(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, 'backend/src/models/sram.c',
                  'static const char *const PART_KEYS[] = {"vcc", NULL}; // "commented"\n'
                  'static const struct x RIPPLE_EXTRA[] = {{"stage", 1}, {NULL, 0}};\n'
                  'static const char *const TIMING_NAMES[] = {"tAA", "tOE", NULL};\n'
                  'static const struct g EXTRA[] = {{"note"}, {"inputMax"}};\n')
            self.assertEqual(pes.source_keys(tmp, 'sram'), {'vcc', 'stage', 'tAA', 'tOE', 'note', 'inputMax'})

    def test_report_skips_indented_arrays_of_loaders_the_kind_never_calls(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, 'backend/src/models/rtc.c', RTC_C)
            write(tmp, 'backend/src/models/converter_load.c', '')
            write(tmp, 'backend/src/models/converter_par.c', '')
            self.assertEqual(pes.source_keys(tmp, 'rtc'), {'model', 'bus', 'seconds', 'vcc', 'tick', 'alarm'})
            self.assertEqual(pes.source_keys(tmp, 'rtc', report=True), {'model', 'bus', 'seconds', 'vcc', 'alarm'})


class InferTests(unittest.TestCase):
    def infer(self, key, *values, pins=frozenset(), known=frozenset()):
        return pes.infer(key, [(v, set(pins)) for v in values], set(known))

    def test_label_splits_camel_case(self):
        self.assertEqual([pes.label(k) for k in ('inputMax', 'tAcc', 'vcc', 'i2cAddress')],
                         ['Input Max', 'T Acc', 'Vcc', 'I2c Address'])

    def test_strings(self):
        self.assertEqual(self.infer('note', 'x'), ('note',))
        self.assertEqual(self.infer('clock', 'CLK', pins={'CLK'}), ('pin',))
        self.assertEqual(self.infer('edge', 'rising'), ('choice', ['rising', 'falling']))
        self.assertEqual(self.infer('edge', 'both'), ('suggested', ['both']))
        self.assertEqual(self.infer('family', 'LS', 'HC', 'HC'), ('suggested', ['HC', 'LS']))
        many = ['v%d' % i for i in range(25)]
        self.assertEqual(self.infer('family', *many), ('text',))
        self.assertEqual(self.infer('card', *many), ('suggested', sorted(many)))
        self.assertEqual(self.infer('title', 'x' * 33), ('text',))

    def test_numbers_bools_and_null(self):
        self.assertEqual(self.infer('volts', 5), ('number', 'V'))
        self.assertEqual(self.infer('gain', 1, 2.5), ('number', ''))
        self.assertEqual(self.infer('bits', 4, 8.0), ('integer',))
        self.assertEqual(self.infer('latching', True), ('bool',))
        self.assertEqual(self.infer('spare', None), ('json',))
        self.assertEqual(self.infer('bits', 4, 'wide'), ('oneOf', [('integer',), ('suggested', ['wide'])]))

    def test_lists(self):
        self.assertEqual(self.infer('vcc', [4.5, 5.5]), ('voltRange',))
        self.assertEqual(self.infer('vcc', [4.5, 5.5, 6]), ('numbers', ''))
        self.assertEqual(self.infer('aliases', []), ('names',))
        self.assertEqual(self.infer('inputs', ['A', 'B'], pins={'A', 'B'}), ('pins',))
        self.assertEqual(self.infer('aliases', ['A', 'Q']), ('names',))
        self.assertEqual(self.infer('steps', [1, 2]), ('numbers', ''))
        self.assertEqual(self.infer('pitch', [2.54]), ('numbers', 'mm'))
        self.assertEqual(self.infer('units', [{'a': 1}, {'b': True}], known={'a', 'b'}),
                         ('list', [('a', ('integer',), False), ('b', ('bool',), False)]))
        self.assertEqual(self.infer('rows', [[1]]), ('listOf', ('numbers', '')))

    def test_dicts(self):
        self.assertEqual(self.infer('timing', {'rise': 3}, {}), ('object', [('rise', ('number', 'ns'), False)]))
        self.assertEqual(self.infer('families', {'HC': {'rise': 3}}),
                         ('map', 'Name', [('rise', ('number', 'ns'), True)]))
        self.assertEqual(self.infer('fields', {'CONFIG.OS': 2}), ('valueMap', 'Name', ('integer',)))

    def test_is_object(self):
        self.assertTrue(pes.is_object([{}], set()))
        self.assertTrue(pes.is_object([{'HC': 1}], {'HC'}))
        self.assertTrue(pes.is_object([{'k%s' % c: 1 for c in 'abcdefghijklmnop'}], set()))
        self.assertFalse(pes.is_object([{'k%s' % c: 1 for c in 'abcdefghijklmnopq'}], set()))
        self.assertFalse(pes.is_object([{'DAC0': 1}], set()))

    def test_fields_marks_keys_every_object_has_as_required(self):
        self.assertEqual(pes.fields([({'b': 1, 'a': 'x'}, set()), ({'b': 2}, set())], set()),
                         [('a', ('suggested', ['x']), False), ('b', ('integer',), True)])


class SwiftTests(unittest.TestCase):
    def test_swift_type_of_every_tag(self):
        def emit(f):
            return 'F_' + f[0]
        cases = [(('text',), '.text'), (('pins',), '.pins'), (('number', 'V'), '.number(unit: "V")'),
                 (('numbers', 'ns'), '.numbers(unit: "ns")'), (('suggested', ['a', 'µ']), '.suggested(["a", "µ"])'),
                 (('choice', ['low']), '.choice(["low"])'), (('object', [('x', ('text',), True)]), '.object([F_x])'),
                 (('list', [('y', ('bool',), False)]), '.list([F_y])'),
                 (('map', 'Name', [('z', ('json',), False)]), '.map(keyLabel: "Name", [F_z])'),
                 (('valueMap', 'Name', ('integer',)), '.valueMap(keyLabel: "Name", .integer)'),
                 (('listOf', ('pin',)), '.listOf(.pin)'), (('oneOf', [('bool',), ('note',)]), '.oneOf([.bool, .note])')]
        for tree, swift in cases:
            self.assertEqual(pes.swift_type(tree, emit), swift)
        with self.assertRaises(ValueError):
            pes.swift_type(('bogus',), emit)

    def test_keys_of_walks_every_nesting(self):
        obj = ('object', [('a', ('list', [('b', ('text',), True)]), True)])
        tree = ('oneOf', [obj, ('map', 'Name', [('c', ('text',), True)]), ('valueMap', 'Name', ('listOf', obj)),
                          ('text',)])
        self.assertEqual(pes.keys_of(tree), {'a', 'b', 'c'})


class AddExtraTests(unittest.TestCase):
    def target(self):
        return [('bus', ('object', [('style', ('text',), True)]), True),
                ('grades', ('list', [('tAA', ('integer',), True)]), True),
                ('regs', ('map', 'Name', []), False),
                ('units', ('listOf', ('object', [])), True),
                ('vcc', ('voltRange',), True)]

    def test_adds_at_top_and_keeps_the_order(self):
        t = self.target()
        pes.add_extra(t, [], 'clock', ('pin',))
        pes.add_extra(t, [], 'vcc', ('text',))
        self.assertEqual([k for k, _, _ in t], ['bus', 'clock', 'grades', 'regs', 'units', 'vcc'])
        self.assertEqual(t[1], ('clock', ('pin',), False))
        self.assertEqual(t[5], ('vcc', ('voltRange',), True))

    def test_adds_under_objects_lists_maps_and_lists_of_objects(self):
        t = self.target()
        for path in (['bus'], ['grades'], ['regs'], ['units']):
            pes.add_extra(t, path, 'extra', ('json',))
        self.assertEqual(t[0][1][1][0], ('extra', ('json',), False))
        self.assertEqual(t[1][1][1][0], ('extra', ('json',), False))
        self.assertEqual(t[2][1][2], [('extra', ('json',), False)])
        self.assertEqual(t[3][1][1][1], [('extra', ('json',), False)])

    def test_refuses_a_path_it_cannot_follow(self):
        with self.assertRaisesRegex(ValueError, r"cannot add under \['vcc'\]"):
            pes.add_extra(self.target(), ['vcc'], 'x', ('text',))
        with self.assertRaisesRegex(ValueError, r"no \['clock'\]"):
            pes.add_extra(self.target(), ['clock'], 'x', ('text',))


class GenerateTests(unittest.TestCase):
    def test_diode_variants_part_variants_and_extra_keys(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, 'backend/src/models/diode.c', DIODE_C)
            write(tmp, 'schematical/schematical/Parts/diode.json', DIODE_JSON)
            os.makedirs(os.path.join(tmp, 'schematical/schematical/Editor'))
            extra = {'diode': [('device', 'seriesR', ('text',), [], ['zener']), ('part', 'vr', ('text',), [])]}
            printed, swift, path = generate(tmp, 'diode', extra)
        self.assertEqual(swift, DIODE_SWIFT)
        self.assertEqual(printed, 'diode: 2 devices, 2 parts, variant type, 8 source keys, missing [] -> %s\n' % path)

    def test_rtc_borrows_the_shared_keys_of_converter(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, 'backend/src/models/rtc.c', RTC_C)
            write(tmp, 'backend/src/models/converter.c',
                  'static const char *const DEVICE_KEYS[] = {"model", "bits", NULL};\n')
            write(tmp, 'backend/src/models/converter_load.c', 'static const char *const BUS_KEYS[] = {"style", NULL};\n')
            write(tmp, 'backend/src/models/converter_par.c', '')
            write(tmp, 'schematical/schematical/Parts/rtc.json', {'devices': [
                {'model': 'ds1307', 'bus': {'style': 'i2c'}, 'pinouts': pins('SCL', 'SDA'),
                 'parts': [{'name': 'DS1307', 'vcc': [4.5, 5.5]}]}]})
            write(tmp, 'schematical/schematical/Parts/converter.json', {'devices': [
                {'model': 'adc0804', 'bus': {'style': 'parallel'}, 'bits': 8, 'pinouts': pins('CS'),
                 'parts': [{'name': 'ADC0804', 'vcc': [4.5, 6.0], 'resets': True}]}]})
            os.makedirs(os.path.join(tmp, 'schematical/schematical/Editor'))
            printed, swift, path = generate(tmp, 'rtc', {})
        self.assertEqual(printed, "rtc: 2 devices, 2 parts, variant model, 8 source keys, missing ['alarm', 'seconds']"
                                  " -> %s\n" % path)
        self.assertIn('enum RtcDraft {\n', swift)
        self.assertIn('Field(key: "style", label: "Style", type: .suggested(["i2c", "parallel"]), required: true)', swift)
        self.assertIn('Field(key: "model", label: "Model", type: .choice(["ds1307"]), required: true)', swift)
        self.assertIn('Field(key: "resets", label: "Resets", type: .bool)\n', swift)
        self.assertIn('Field(key: "vcc", label: "Vcc", type: .voltRange, required: true)\n', swift)
        self.assertIn('        variantKey: "model",\n', swift)

    def test_a_kind_without_a_variant_key(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, 'backend/src/models/relay.c', 'static const char *const DEVICE_KEYS[] = {"type", NULL};\n')
            write(tmp, 'schematical/schematical/Parts/relay.json', {'devices': [
                {'type': 'reed', 'pinouts': pins('A'), 'parts': [{'name': 'K1'}]}]})
            os.makedirs(os.path.join(tmp, 'schematical/schematical/Editor'))
            printed, swift, _ = generate(tmp, 'relay', {})
        self.assertIn('Field(key: "type", label: "Type", type: .suggested(["reed"]), required: true)', swift)
        self.assertIn('        variantKey: nil,\n', swift)
        self.assertIn('        part: []\n', swift)
        self.assertTrue(printed.startswith('relay: 1 devices, 1 parts, variant None, 1 source keys, missing [] -> '))

    def test_extra_data_file_is_loaded(self):
        self.assertEqual(pes.EXTRA['mux'], [('device', 'output', ('choice', ['push-pull', 'open-drain']), [])])
        self.assertIs(pes.EXTRA['rtc'], pes.EXTRA['converter'])
        self.assertEqual([e[1] for e in pes.EXTRA['eeprom']][-5:], ['tas', 'tch', 'tcs', 'toes', 'toh'])


class CommittedDraftTests(unittest.TestCase):
    """generate() over the checkout's Parts and backend sources, into a temporary repo."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        real_repo(cls.tmp.name)

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_generated_drafts_equal_the_committed_ones(self):
        kinds = [k for k in pes.KIND_FILES if k not in HAND_EDITED]
        self.assertEqual(len(kinds), len(pes.KIND_FILES) - 10)
        self.assertIn('converter', kinds)  # its loader's keys are in split pieces (plan-68-U Corrections)
        for kind in kinds:
            with self.subTest(kind=kind):
                printed, swift, path = generate(self.tmp.name, kind, pes.EXTRA)
                self.assertTrue(printed.startswith(kind + ': '))
                self.assertTrue(printed.endswith(' -> %s\n' % path))
                self.assertEqual(swift, committed(path))

    def test_hand_edited_drafts_still_differ_from_the_generator(self):
        for kind in sorted(HAND_EDITED):
            with self.subTest(kind=kind):
                _, swift, path = generate(self.tmp.name, kind, pes.EXTRA)
                self.assertTrue(swift.startswith('import Foundation\n\n// Generated by scripts/part-editor-schema.py'))
                self.assertNotEqual(swift, committed(path), 'regenerated by hand: drop it from HAND_EDITED')

    def test_split_pieces_are_read_but_not_listed(self):
        # converter_load.c's pieces (plan-68-J) hold the command keys; the header names the kind's own files.
        files = pes.kind_files(support.REPO, 'converter')
        self.assertIn('converter_load_proto.c', files)
        self.assertLess(files.index('converter_load.c'), files.index('converter_load_proto.c'))
        _, swift, _ = generate(self.tmp.name, 'converter', pes.EXTRA)
        self.assertIn('(converter.c, converter_load.c, converter_par.c) and', swift)


class CommandLineTests(unittest.TestCase):
    def test_writes_each_kind_named(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = real_repo(tmp)
            r = support.run('part-editor-schema.py', repo, 'mux', 'latch')
            self.assertEqual(r.returncode, 0, r.stderr)
            lines = r.stdout.splitlines()
            self.assertEqual(len(lines), 2)
            for line, kind, name in zip(lines, ('mux', 'latch'), ('MuxDraft', 'LatchDraft')):
                path = os.path.join(repo, 'schematical/schematical/Editor/%s.swift' % name)
                self.assertTrue(line.startswith(kind + ': ') and line.endswith(' -> ' + path), line)
                with open(path) as fh:
                    self.assertEqual(fh.read(), committed(path))

    def test_an_unknown_kind_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            r = support.run('part-editor-schema.py', real_repo(tmp), 'nosuchkind')
        self.assertEqual(r.returncode, 1)
        self.assertTrue(r.stderr.rstrip().endswith('FileNotFoundError: [Errno 2] No such file or directory: '
                                                   "'%s/schematical/schematical/Parts/nosuchkind.json'" % tmp), r.stderr)


