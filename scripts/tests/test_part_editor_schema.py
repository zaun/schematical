def write(root, rel, text):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text if isinstance(text, str) else json.dumps(text))


def real_repo(tmp):
    """A repo whose Parts and backend sources are the checkout's, with an empty Editor folder."""
    os.makedirs(os.path.join(tmp, 'schematical', 'schematical', 'Editor'))
    os.makedirs(os.path.join(tmp, 'backend'))
    os.symlink(os.path.join(support.REPO, 'schematical', 'schematical', 'Parts'),
               os.path.join(tmp, 'schematical', 'schematical', 'Parts'))
    os.symlink(os.path.join(support.REPO, 'backend', 'src'), os.path.join(tmp, 'backend', 'src'))
    return tmp


def generate(repo, kind, extra):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        pes.generate(repo, kind, extra)
    path = os.path.join(repo, 'schematical', 'schematical', 'Editor',
                        pes.NAMES.get(kind, kind[:1].upper() + kind[1:]) + 'Draft.swift')
    with open(path) as fh:
        return out.getvalue(), fh.read(), path


def committed(path):
    with open(os.path.join(EDITOR, os.path.basename(path))) as fh:
        return fh.read()


def pins(*names):
    return {'p': [{'number': i + 1, 'name': n, 'role': 'input'} for i, n in enumerate(names)]}


