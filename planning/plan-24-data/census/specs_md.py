#!/usr/bin/env python3
"""Generate planning/plan-24-data/specs.md: one section per device spec in specs/.

The device itself (the plan-24-D §3 form, schema.md) is the JSON file; this index gives
each device's datasheet, bus, counts, conversion and not-modeled list for a reader.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.dirname(HERE)
SPECS = os.path.join(DATA, 'specs')

def bus_text(b):
    st = b.get('style')
    if st == 'spi':
        return f"SPI mode {b.get('mode', 0)}" + (' (2-wire, no CS)' if 'cs' not in b else '') + \
               ('' if 'miso' in b else ', write-only') + ('' if 'mosi' in b else ', read-only')
    if st == 'i2c':
        t = [x for x in b.get('table', []) if x is not None]
        return 'I2C ' + ', '.join(f'0x{x:02X}' for x in t)
    if st == 'i2c-spi':
        return 'I2C/SPI'
    if st == 'parallel':
        return f"parallel {len(b.get('data', []))}-bit"
    if st == 'clocked':
        return f"clocked {len(b.get('data', []))}-bit"
    return str(st)

def conv_text(c):
    if not c:
        return '—'
    t = c.get('time')
    if isinstance(t, dict):
        vals = list(t.get('values', {}).values())
        t = f"{min(vals):g}–{max(vals):g} ns by {t.get('field') or '+'.join(t.get('fields', []))}" if vals else '?'
    else:
        t = f'{t:g} ns'
    return f"{t}; start {', '.join(c.get('start', []))}"

out = ['# plan-24 device specs', '',
       'One section per device. The device itself — pins, bus, registers, protocol, '
       'conversion, ready pins, DAC registers, clock — is `specs/<ID>.json` in the form '
       '`schema.md` defines (plan-24-D §3, plan-24-F §2); this file indexes them. '
       'Generated by `census/specs_md.py`; do not edit by hand.', '']
groups = {'ADC': [], 'DAC': [], 'RTC': []}
for f in sorted(os.listdir(SPECS)):
    if f.endswith('.json'):
        sp = json.load(open(os.path.join(SPECS, f)))
        groups.setdefault(sp['device'].get('function', '?'), []).append(sp)
for g, sps in groups.items():
    if not sps:
        continue
    out += [f'## {g} ({len(sps)} devices)', '']
    for sp in sps:
        d = sp['device']
        regs = d.get('registers', [])
        cmds = d.get('protocol', {}).get('commands', [])
        out.append(f"### {d['id']}")
        out.append('')
        out.append(f"{d.get('description', '')}. `specs/{d['id']}.json`; datasheet `{sp.get('pdf')}` "
                   f"({sp.get('pages', '')}).")
        out.append('')
        line = f"- Bus: {bus_text(d.get('bus', {}))}"
        if 'configBus' in d:
            line += f"; config {bus_text(d['configBus'])}"
        out.append(line)
        if g != 'RTC':
            cf = d.get('codeFormat', '—')
            out.append(f"- {d.get('bits')} bits, {d.get('channels')} channel(s), code "
                       f"{cf if isinstance(cf, str) else 'by ' + (cf.get('pin') or cf.get('field', ''))}; "
                       f"vcc {d.get('vcc')}")
        else:
            out.append(f"- vcc {d.get('vcc')}")
        out.append(f"- {len(regs)} registers, {len(cmds)} commands; frame {d.get('protocol', {}).get('frame')}")
        if g == 'ADC':
            out.append(f"- Conversion: {conv_text(d.get('conversion'))}")
        rd = d.get('ready', [])
        if rd:
            out.append('- Ready: ' + ', '.join(sorted({r['pin'] for r in rd})))
        out.append('- Packages: ' + ', '.join(f"{k} ({v['footprint']})" for k, v in sp.get('packages', {}).items()))
        nm = sp.get('notModeled', [])
        if nm:
            out.append('- Not modeled:')
            out += [f'  - {x}' for x in nm]
        out.append('')
open(os.path.join(DATA, 'specs.md'), 'w').write('\n'.join(out))
print({g: len(v) for g, v in groups.items()})
