static void expect_error(const char *what, const char *text, const char *want) {
    PartLibrary *lib = fixture_library();
    char *error = load(lib, text, "register.json");
    int ok = error != NULL && strstr(error, want) != NULL;

    if (!ok) {
        printf("  %s\n  error: %s\n  want: %s\n", what, error != NULL ? error : "(none)", want);
        failures++;
    }
    free(error);
    part_library_destroy(lib);
}

#define BAD_PINS \
    "{'format':'schematical-parts','version':1,'kind':'register','devices':[{'id':'bad'," \
    "'function':'Register','description':'d','drawer':[],'pinouts':{'p6':[" \
    "{'number':1,'name':'D1','role':'input'},{'number':2,'name':'D2','role':'input'}," \
    "{'number':3,'name':'CLK','role':'input'},{'number':4,'name':'Q1','role':'output'}," \
    "{'number':5,'name':'Q2','role':'output'},{'number':6,'name':'OE','role':'input'}]},"
#define BAD_HEAD BAD_PINS "'model':'parallel',"
#define BAD_TAIL "'timing':{'HC':{'rise':1,'fall':1,'vcc':[2,6]}},'parts':[]}]}"
#define CLK "'clk':{'pin':'CLK','edge':'rising'}"
#define BANK2 "'outputs':[{'q':['Q1','Q2']}]"

/* A device whose groups are n copies of group (text without braces). */
static char *groups_of(size_t n, const char *group) {
    size_t len = strlen(BAD_HEAD) + strlen(BAD_TAIL) + n * (strlen(group) + 4) + 32;
    char *text = malloc(len);
    size_t i;

    snprintf(text, len, "%s'groups':[", BAD_HEAD);
    for (i = 0; i < n; i++) {
        strcat(text, i > 0 ? ",{" : "{");
        strcat(text, group);
        strcat(text, "}");
    }
    strcat(text, "],");
    strcat(text, BAD_TAIL);
    return text;
}

/* "'d':[...n names...],'outputs':[{'q':[...n names...]}]," with clk. */
static char *wide_group(size_t n) {
    size_t len = n * 24 + 128;
    char *text = malloc(len);
    size_t i;

    strcpy(text, "'d':[");
    for (i = 0; i < n; i++) {
        snprintf(text + strlen(text), len - strlen(text), "%s'D%zu'", i > 0 ? "," : "", i);
    }
    strcat(text, "]," CLK ",'outputs':[{'q':[");
    for (i = 0; i < n; i++) {
        snprintf(text + strlen(text), len - strlen(text), "%s'Q%zu'", i > 0 ? "," : "", i);
    }
    strcat(text, "]}]");
    return text;
}

