import CoreGraphics
import Foundation
import XCTest
@testable import schematical

/// `BoardSettings`' edits on a hand-built board, with no document
/// (plan-68-E): size and type, outline, grid, layers, stackup, rules, net
/// classes and groups.
@MainActor
final class BoardSettingsEditTests: XCTestCase {
    func testSizeFollowsTheType() {
        var board = BoardSettings()
        board.setSize(width: 100_000, height: -5)
        XCTAssertEqual(board.width, BoardSettings.sizeRange.upperBound)
        XCTAssertEqual(board.height, BoardSettings.sizeRange.lowerBound)
        board.setType(.isa8)
        let card = try! XCTUnwrap(board.card)
        XCTAssertEqual(board.height, card.height)
        board.setSize(width: 1, height: 1)
        XCTAssertEqual(board.width, card.minimumLength)
        XCTAssertEqual(board.height, card.height)
        board.setType(.isa8)
        board.setType(.customCard)
        let custom = board.customCard.clamped()
        board.setSize(width: 0, height: 0)
        XCTAssertEqual(board.width, custom.indent + custom.tabLength)
        XCTAssertEqual(board.height, custom.depth + 1)
        XCTAssertEqual(board.layers, 2, "fingers on both sides")
        var wider = custom
        wider.indent += 50
        board.setCustomCard(wider)
        XCTAssertEqual(board.width, wider.clamped().indent + wider.clamped().tabLength)
        board.setType(.custom)
        board.setCustomCard(custom)
        XCTAssertEqual(board.customCard, custom.clamped(), "kept, though the board is no card now")
        // A free-form outline fixes the size.
        board.setOutline([.zero, CGPoint(x: 40, y: 0), CGPoint(x: 40, y: 30), CGPoint(x: 0, y: 30)])
        XCTAssertEqual(board.width, 40)
        board.setSize(width: 80, height: 80)
        XCTAssertEqual(board.width, 40)
        board.resetOutline()
        board.resetOutline()
        XCTAssertNil(board.customOutline)
    }

    func testCardOptionsGridAndLayers() throws {
        var board = BoardSettings()
        board.setType(.pcie)
        var options = board.cardOptions
        board.setCardOptions(options)
        options["lanes"] = options["lanes"] == .number(4) ? .number(1) : .number(4)
        board.setCardOptions(options)
        XCTAssertEqual(board.cardOptions, options)
        board.setType(.custom)
        options["lanes"] = options["lanes"] == .number(4) ? .number(1) : .number(4)
        board.setCardOptions(options)
        XCTAssertEqual(board.cardOptions, options, "stored, though Custom has no options")
        board.setGrid(1_000)
        XCTAssertEqual(board.grid, BoardSettings.gridRange.upperBound)
        board.setGrid(1_000)

        XCTAssertNotNil(board.layerCountProblem(3, bottomItems: false, traceLayers: [], pourLayers: [], hasVias: false))
        XCTAssertNotNil(board.layerCountProblem(1, bottomItems: true, traceLayers: [], pourLayers: [], hasVias: false))
        XCTAssertNotNil(board.layerCountProblem(1, bottomItems: false, traceLayers: [.bottom], pourLayers: [], hasVias: false))
        XCTAssertNotNil(board.layerCountProblem(1, bottomItems: false, traceLayers: [], pourLayers: [.bottom], hasVias: false))
        XCTAssertNotNil(board.layerCountProblem(1, bottomItems: false, traceLayers: [], pourLayers: [], hasVias: true))
        XCTAssertNil(board.layerCountProblem(1, bottomItems: false, traceLayers: [.top], pourLayers: [], hasVias: false))
        board.setType(.isa8)
        XCTAssertNotNil(board.layerCountProblem(1, bottomItems: false, traceLayers: [], pourLayers: [], hasVias: false))
    }

    func testLayerStylesAndStackup() {
        var board = BoardSettings()
        board.layers = 4
        let inner = CopperLayer.inner(2)
        XCTAssertNotNil(board.layerTypeProblem(.inner(5), .wire, hasTraces: false, hasPours: false))
        XCTAssertNotNil(board.layerTypeProblem(.top, .wire, hasTraces: false, hasPours: false))
        XCTAssertNotNil(board.layerTypeProblem(inner, .component, hasTraces: false, hasPours: false))
        XCTAssertNotNil(board.layerTypeProblem(inner, .plane, hasTraces: true, hasPours: false))
        XCTAssertNotNil(board.layerTypeProblem(inner, .plane, hasTraces: false, hasPours: true))
        XCTAssertNil(board.layerTypeProblem(inner, .plane, hasTraces: false, hasPours: false))
        board.setLayerType(inner, .wire)
        XCTAssertNil(board.traceLayerRefusal(inner))
        board.setLayerType(inner, .plane)
        XCTAssertEqual(board.style(of: inner).type, .plane)
        XCTAssertNotNil(board.traceLayerRefusal(inner))
        XCTAssertNotNil(board.traceLayerRefusal(.inner(5)))
        board.setLayerNet(inner, .ground)
        board.setLayerNet(.top, .ground)
        XCTAssertEqual(board.style(of: inner).net, .ground)
        XCTAssertNil(board.style(of: .top).net, "only an inner layer has a net")
        board.setLayerClearance(inner, 1_000)
        XCTAssertEqual(board.style(of: inner).clearance, LayerStyle.clearanceRange.upperBound)
        board.setLayerClearance(inner, nil)
        XCTAssertNil(board.style(of: inner).clearance)
        let color = board.style(of: .top).color
        board.setLayerColor(.top, color)
        board.setLayerColor(.inner(5), color)

        board.setTemperatureRise(10_000)
        XCTAssertEqual(board.stackup.temperatureRise, BoardStackup.temperatureRiseRange.upperBound)
        board.setTemperatureRise(10_000)
        board.setCopperThickness(-1, at: 0)
        XCTAssertEqual(board.stackup.copper[0], BoardStackup.copperRange.lowerBound)
        board.setCopperThickness(-1, at: 0)
        board.setCopperThickness(1, at: 99)
        board.setDielectric(at: 0, kind: nil, thickness: 10_000, er: -1)
        XCTAssertEqual(board.stackup.dielectrics[0].thickness, BoardStackup.thicknessRange.upperBound)
        XCTAssertEqual(board.stackup.dielectrics[0].er, BoardStackup.erRange.lowerBound)
        board.setDielectric(at: 0, kind: board.stackup.dielectrics[0].kind, thickness: nil, er: nil)
        board.setDielectric(at: 99, kind: nil, thickness: 1, er: 1)
        board.resetStackup()
        XCTAssertEqual(board.stackup, BoardStackup.standard(layers: 4))
        board.resetStackup()

        var rules = board.rules
        rules[keyPath: DesignRules.groups[0].rules[0].field] = -.infinity
        board.setDesignRules(rules, manufacturer: board.rulesManufacturer)
        XCTAssertEqual(board.rules[keyPath: DesignRules.groups[0].rules[0].field], 0)
        board.setDesignRules(board.rules, manufacturer: board.rulesManufacturer)
    }

    func testNetClasses() {
        var board = BoardSettings()
        XCTAssertNil(BoardSettings.netClassName("  "))
        XCTAssertEqual(BoardSettings.netClassName(String(repeating: "x", count: 100))?.count, NetClass.nameLength.upperBound)
        let power = board.addNetClass(named: "  ")
        let signal = board.addNetClass(named: "Signal")
        XCTAssertEqual(board.netClasses.map(\.name), ["Class", "Signal"])
        board.renameNetClass(power, to: "Power")
        board.renameNetClass(power, to: "Power")
        board.renameNetClass(power, to: " ")
        board.renameNetClass(UUID(), to: "X")
        XCTAssertEqual(board.netClasses[0].name, "Power")
        board.setNetClassWidth(power, 100_000)
        board.setNetClassWidth(power, 100_000)
        board.setNetClassWidth(UUID(), 1)
        XCTAssertEqual(board.netClasses[0].width, BoardTrace.widthRange.upperBound)
        board.setNetClassClearance(power, 100)
        board.setNetClassClearance(power, 100)
        board.setNetClassClearance(UUID(), 1)
        XCTAssertEqual(board.netClasses[0].clearance, LayerStyle.clearanceRange.upperBound)
        board.setNetClassVia(power, drill: 0, diameter: 0)
        board.setNetClassVia(power, drill: 0, diameter: 0)
        board.setNetClassVia(UUID(), drill: 1, diameter: 1)
        XCTAssertEqual(board.netClasses[0].viaDrill, BoardVia.drillRange.lowerBound)
        XCTAssertGreaterThanOrEqual(board.netClasses[0].viaDiameter, board.netClasses[0].viaDrill + 2 * BoardVia.minimumRing)
        board.assignNet(.ground, toClass: power)
        board.assignNet(.ground, toClass: signal)
        XCTAssertEqual(board.netClasses.map(\.members), [[], [.ground]])
        board.assignNet(.ground, toClass: nil)
        XCTAssertEqual(board.netClasses.map(\.members), [[], []])
        board.moveNetClass(power, to: 99)
        XCTAssertEqual(board.netClasses.map(\.id), [signal, power])
        board.moveNetClass(power, to: 99)
        board.moveNetClass(UUID(), to: 0)
        let rule = LayerRule(mode: .only, layers: [.top])
        board.setNetClassLayerRule(power, LayerRule(mode: .only, layers: []))
        board.setNetClassLayerRule(power, rule)
        board.setNetClassLayerRule(power, rule)
        XCTAssertEqual(board.netClasses[1].layerRule, rule)
        board.removeNetClass(power)
        XCTAssertEqual(board.netClasses.map(\.id), [signal])
    }

    func testNetOverridesAndGroups() {
        var board = BoardSettings()
        let rule = LayerRule(mode: .prefer, layers: [.bottom])
        board.setNetLayerRule(.ground, LayerRule(mode: .only, layers: []))
        XCTAssertTrue(board.netOverrides.isEmpty)
        board.setNetLayerRule(.ground, rule)
        board.setNetLayerRule(.ground, rule)
        board.setNetLayerRule(.ground, LayerRule(mode: .only, layers: [.top]))
        XCTAssertEqual(board.netOverrides.count, 1)
        XCTAssertEqual(board.netOverrides[0].layerRule?.mode, .only)
        board.setNetLayerRule(.ground, nil)
        XCTAssertTrue(board.netOverrides.isEmpty)

        let pair = board.addNetGroup(named: "", mode: .diffPair)
        let bus = board.addNetGroup(named: "DATA", mode: .lengthMatch)
        XCTAssertEqual(board.netGroups.map(\.name), ["Group", "DATA"])
        board.renameNetGroup(pair, to: "USB")
        board.renameNetGroup(pair, to: "USB")
        board.renameNetGroup(UUID(), to: "X")
        let nets: [PlaneNet] = [.ground, .rail(mv: 5000), .rail(mv: 3300)]
        for net in nets { board.assignNet(net, toGroup: bus) }
        board.assignNet(.ground, toGroup: bus)
        board.assignNet(.ground, toGroup: UUID())
        XCTAssertEqual(board.netGroups[1].members, nets)
        XCTAssertNotNil(board.netGroupModeProblem(bus, .diffPair))
        XCTAssertNil(board.netGroupModeProblem(bus, .lengthMatch))
        XCTAssertNil(board.netGroupModeProblem(UUID(), .diffPair))
        board.setNetGroupMode(bus, .lengthMatch)
        board.setNetGroupMode(pair, .lengthMatch)
        XCTAssertEqual(board.netGroups[0].mode, .lengthMatch)
        board.setNetGroupMode(pair, .diffPair)
        board.assignNet(.ground, toGroup: pair)
        board.assignNet(.rail(mv: 5000), toGroup: pair)
        XCTAssertEqual(board.netGroups[0].members, [.ground, .rail(mv: 5000)])
        XCTAssertEqual(board.netGroups[1].members, [.rail(mv: 3300)], "a net is in one group")
        XCTAssertNotNil(board.netGroupJoinProblem(.rail(mv: 3300), pair))
        XCTAssertNil(board.netGroupJoinProblem(.ground, pair), "already in it")
        XCTAssertNil(board.netGroupJoinProblem(.ground, UUID()))
        board.setNetGroupValue(pair, \.gap, 1_000, NetGroup.gapRange)
        board.setNetGroupValue(pair, \.gap, 1_000, NetGroup.gapRange)
        board.setNetGroupValue(UUID(), \.gap, 1, NetGroup.gapRange)
        XCTAssertEqual(board.netGroups[0].gap, NetGroup.gapRange.upperBound)
        board.unassignNet(.ground)
        XCTAssertEqual(board.netGroups[0].members, [.rail(mv: 5000)])
        board.removeNetGroup(bus)
        XCTAssertEqual(board.netGroups.map(\.id), [pair])
    }

    /// A class's rules and layer rule, an override and a group, for a net
    /// two wired LEDs make (its copper from a document's connectivity).
    func testRulesOfAWiredNet() throws {
        let doc = TestSupport.newDocument()
        let one = try TestSupport.place(doc, "GENERIC-LED", at: CGPoint(x: 100, y: 100))
        let two = try TestSupport.place(doc, "GENERIC-LED", at: CGPoint(x: 400, y: 200))
        let k = try TestSupport.pin(one, "K"), a = try TestSupport.pin(two, "A")
        XCTAssertNil(doc.connect(.pin(k), .pin(a)))
        let member = PlaneNet.pin(chip: one.id, designator: one.part.pins[k.index].designator)
        let copper = doc.connectivity()
        let net = try XCTUnwrap(copper.net(of: member))
        var board = BoardSettings()
        let power = board.addNetClass(named: "Power")
        board.setNetClassWidth(power, 40)
        board.assignNet(member, toClass: power)
        XCTAssertEqual(board.netClass(ofNet: net, in: copper)?.id, power)
        XCTAssertEqual(board.netRules(ofNet: net, in: copper).width, 40)
        XCTAssertNil(board.effectiveLayers(ofNet: net, in: copper).rule)
        board.setNetClassLayerRule(power, LayerRule(mode: .prefer, layers: [.bottom]))
        XCTAssertEqual(board.effectiveLayers(ofNet: net, in: copper).preferred, [.bottom])
        board.setNetLayerRule(member, LayerRule(mode: .only, layers: [.top]))
        XCTAssertEqual(board.effectiveLayers(ofNet: net, in: copper).allowed, [.top])
        let group = board.addNetGroup(named: "G", mode: .lengthMatch)
        board.assignNet(member, toGroup: group)
        XCTAssertEqual(board.group(ofNet: net, in: copper)?.id, group)
    }

    /// The rules of a net need its copper: a document's connectivity.
    func testRulesOfANet() {
        let doc = TestSupport.newDocument()
        let copper = doc.connectivity()
        var board = BoardSettings()
        XCTAssertNil(board.netClass(ofNet: 0, in: copper))
        XCTAssertEqual(board.netRules(ofNet: nil, in: copper), NetRules.defaults(for: board.rules))
        XCTAssertEqual(board.netRules(ofNet: 0, in: copper), NetRules.defaults(for: board.rules))
        XCTAssertNil(board.layerRule(ofNet: 0, in: copper))
        XCTAssertNil(board.group(ofNet: 0, in: copper))
        XCTAssertNil(board.effectiveLayers(ofNet: 0, in: copper).rule)
        board.netOverrides = [NetOverride(net: .ground, layerRule: LayerRule(mode: .only, layers: [.top]))]
        XCTAssertNil(board.layerRule(ofNet: 0, in: copper), "no copper of the ground net")
    }
